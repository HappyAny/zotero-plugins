const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../../..'),style=path.join(root,'zotero-style-custom');
const out=path.join(root,'build/validation/workbench-dismiss');fs.mkdirSync(out,{recursive:true});
const acorn=require('acorn');
const {chromium}=require('playwright');
const read=name=>fs.readFileSync(path.join(style,name),'utf8');
const source=read('scripts/design-preview.mjs');
const fn=acorn.parse(source,{ecmaVersion:'latest',sourceType:'module'}).body.find(n=>n.type==='FunctionDeclaration'&&n.id.name==='mountDemo');
const demo=source.slice(fn.start,fn.end).replace('const bench=Workbench.attach(win,',
 "runtime.i18n=CustomStyleI18N;runtime.t=text=>CustomStyleI18N.t(text);runtime.pref=(key,fallback)=>key==='language'?'zh-CN':fallback;const bench=Workbench.attach(win,");
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME||undefined,headless:true});
 const receipt={errors:[],networkRequests:[],checks:[]};
 const check=(name,actual)=>{assert.equal(actual,true,name);receipt.checks.push({name,pass:true});};
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>receipt.errors.push(e.message));
  await page.route(/^https?:/,route=>{receipt.networkRequests.push(route.request().url().split('?')[0]);return route.abort();});
  await page.setContent('<html lang="zh-CN"><body style="margin:0;background:#eef0f3;font:14px system-ui"><div id="zotero-items-toolbar" style="position:fixed;left:8px;top:8px"></div><button id="outside" style="position:fixed;left:8px;bottom:8px">外侧操作</button><iframe id="outside-frame" style="position:fixed;left:8px;top:80px;width:130px;height:130px" srcdoc="<button id=target>PDF 区域</button>"></iframe></body></html>');
  await page.addStyleTag({content:read('content/workbench.css')});
  for(const name of ['i18n','strings','workspace','reading-path','paper-graph','journal-identity','reader-tools','workbench'])await page.addScriptTag({content:read('src/'+name+'.js')});
  await page.evaluate(()=>{
   CustomStyleI18N.load(CustomStyleStrings);CustomStyleI18N.use('zh-CN');
   document.getElementById('outside').addEventListener('mousedown',e=>{globalThis.outsideDelivered=(globalThis.outsideDelivered||0)+1;globalThis.pressPrevented=e.defaultPrevented;e.stopPropagation();});
   globalThis.openerFocuses=0;document.getElementById('outside').addEventListener('focus',()=>openerFocuses++);
   let current=null;
   window.Zotero_Tabs={add(spec){current=spec;const container=document.createElement('div');container.className='tab-container';document.body.append(container);return {id:'demo-tab',container};},select(){},close(){const old=current;current=null;old?.onClose();}};
  });
  await page.addScriptTag({content:demo+'\nglobalThis.mountDismissDemo=mountDemo;'});
  await page.locator('#outside').focus();
  await page.evaluate(async()=>{globalThis.demo=await mountDismissDemo(window,CustomStyleWorkbench,CustomStyleWorkspace,CustomStyleReadingPath,CustomStylePaperGraph,CustomStyleJournalIdentity);const p=demo.bench.panel;Object.assign(p.style,{left:'180px',right:'auto',top:'55px',bottom:'auto',width:'1080px',height:'870px'});});
  const panel=page.locator('#style-custom-workbench');
  await panel.locator('input[type=search]').first().click();
  check('inside click stays open',await panel.isVisible());
  const focused=await page.evaluate(()=>openerFocuses);
  await page.locator('#outside').click();
  check('outside click dismisses through capture',!(await panel.isVisible()));
  check('outside action runs and receives focus once',await page.evaluate(n=>outsideDelivered===1&&!pressPrevented&&document.activeElement.id==='outside'&&openerFocuses===n+1,focused));
  await page.locator('#style-custom-workbench-button').click();
  check('toolbar reopens after dismissal',await panel.isVisible());
  await page.locator('#style-custom-workbench-button').click();
  check('toolbar closes without reopening',!(await panel.isVisible()));
  await page.locator('#style-custom-workbench-button').click();
  await page.evaluate(()=>demo.bench.dock());
  await page.locator('#outside').click();
  check('docked panel ignores outside click',await panel.isVisible());
  await page.evaluate(()=>demo.bench.undock());
  await page.locator('#outside').click();
  check('undocking restores outside dismissal',!(await panel.isVisible()));
  await page.evaluate(()=>demo.bench.show('explore'));
  await page.evaluate(()=>{const f=document.createElement('iframe');f.id='inside-frame';f.srcdoc='<button id="target">内部预览</button>';f.style.cssText='position:absolute;left:300px;top:100px;width:160px;height:80px;z-index:20';demo.bench.panel.append(f);});
  await page.frameLocator('#inside-frame').locator('#target').click();
  await page.waitForTimeout(30);
  check('internal iframe stays open',await panel.isVisible());
  await page.frameLocator('#outside-frame').locator('#target').click();
  await panel.waitFor({state:'hidden',timeout:1500});
  check('outside PDF iframe dismisses',!(await panel.isVisible()));
  await page.evaluate(()=>document.getElementById('inside-frame').remove());
  await page.evaluate(()=>demo.bench.show('explore'));
  await panel.locator('input[type=search]').first().click();
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  await page.waitForTimeout(30);
  check('ordinary window blur stays open',await panel.isVisible());
  const header=panel.locator('.sc-header').first();
  const box=await header.boundingBox();assert.ok(box);
  await page.mouse.move(box.x+350,box.y+20);await page.mouse.down();await page.mouse.move(100,970);await page.mouse.up();
  check('dragging from inside to outside stays open',await panel.isVisible());
  await page.evaluate(()=>Object.assign(demo.bench.panel.style,{left:'180px',right:'auto',top:'55px',bottom:'auto',width:'1080px',height:'870px'}));
  await page.screenshot({path:path.join(out,'floating-workbench.png')});
  await page.locator('#outside').click();
  check('reopened panel still dismisses',!(await panel.isVisible()));
  await page.evaluate(()=>demo.bench.destroy());
  assert.deepEqual(receipt.errors,[]);assert.deepEqual(receipt.networkRequests,[]);
  fs.writeFileSync(path.join(out,'browser.json'),JSON.stringify(receipt,null,2)+'\n');
  console.log(JSON.stringify(receipt));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
