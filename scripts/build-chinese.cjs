/* Compile Chinese messages without changing interpolation expressions or data keys. */
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
let acorn;
try { acorn=require('acorn'); }
catch { acorn=require(path.join(root,'build/chinese-localization/node_modules/acorn')); }
const source=fs.readFileSync(path.join(root,'content/i18n.js'),'utf8');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'data/zotpop-zh-CN.json'),'utf8'));
const tree=acorn.parse(source,{ecmaVersion:'latest'});
let strings,explain;
function find(node){
 if(!node||typeof node!=='object')return;
 if(node.type==='VariableDeclarator'&&node.id.name==='STRINGS')strings=node.init;
 if(node.type==='VariableDeclarator'&&node.id.name==='EXPLAIN')explain=node.init;
 for(const value of Object.values(node))if(Array.isArray(value))value.forEach(find);else if(value&&typeof value==='object')find(value);
}
find(tree);
const english=object=>object.properties.find(p=>(p.key.name||p.key.value)==='en').value;
const patches=[];
function translated(text){
 if(!(text in catalog))throw new Error('Missing Chinese message: '+text);
 const holes=s=>(s.match(/\{\d+\}/g)||[]).sort().join(',');
 if(holes(text)!==holes(catalog[text]))throw new Error('Changed interpolation fields: '+text);
 return catalog[text];
}
function collect(node,parent){
 if(!node||typeof node!=='object')return;
 if(node.type==='Property'){
  if((node.key.name||node.key.value)==='csvHead')return;
  return collect(node.value,node);
 }
 if(node.type==='TemplateLiteral'){
  const text=node.quasis.map((q,i)=>(q.value.cooked??q.value.raw)+(i<node.expressions.length?'{'+i+'}':'')).join('');
  if(/[A-Za-z]/.test(text.replace(/\{\d+\}/g,'')))patches.push({start:node.start,end:node.end,type:'template',text,expressions:node.expressions});
  node.expressions.forEach(n=>collect(n,node));return;
 }
 if(node.type==='Literal'&&typeof node.value==='string'&&/[A-Za-z]/.test(node.value)){
  if(parent&&['BinaryExpression','MemberExpression','RegExpLiteral'].includes(parent.type))return;
  if(node.value==='s'||/^https?:|^chrome:|^\.[a-z]+$/.test(node.value))return;
  patches.push({start:node.start,end:node.end,type:'literal',text:node.value});return;
 }
 for(const[k,value]of Object.entries(node)){
  if(['key','params','id'].includes(k))continue;
  if(Array.isArray(value))value.forEach(n=>collect(n,node));else if(value&&typeof value==='object')collect(value,node);
 }
}
const objects=[english(strings),english(explain)];
objects.forEach(n=>collect(n,null));patches.sort((a,b)=>a.start-b.start||b.end-a.end);
const BT=String.fromCharCode(96), INTERPOLATION='$'+'{';
function render(start,end){
 let out='',cursor=start;
 for(const p of patches){
  if(p.start<cursor||p.end>end)continue;
  out+=source.slice(cursor,p.start);
  if(p.type==='literal')out+=JSON.stringify(translated(p.text));
  else {
   const text=translated(p.text).replace(/\\/g,'\\\\').split(BT).join('\\'+BT).split(INTERPOLATION).join('\\'+INTERPOLATION);
   out+=BT+text.replace(/\{(\d+)\}/g,(_,i)=>INTERPOLATION+render(p.expressions[Number(i)].start,p.expressions[Number(i)].end)+'}')+BT;
  }
  cursor=p.end;
 }
 return out+source.slice(cursor,end);
}
const output='/* Generated by scripts/build-chinese.cjs. Edit data/zotpop-zh-CN.json. */\n'+
 '(function(root){\n"use strict";\nfunction create({groupDigits,plural,isOne}){\nreturn {strings:'+render(objects[0].start,objects[0].end)+',errors:'+render(objects[1].start,objects[1].end)+'};\n}\n'+
 'if(typeof module!=="undefined"&&module.exports)module.exports=create;\nroot.ZotPoPChinese=create;\n})(typeof globalThis!=="undefined"?globalThis:this);\n';
new (require('node:vm').Script)(output);
fs.writeFileSync(path.join(root,'content/i18n-zh.js'),output);
console.log(JSON.stringify({chineseFragments:Object.keys(catalog).length,interpolatedFragments:patches.length}));
